//go:build linux

// Package jobrecorder composes a single borrowed jobs.Job observation with a
// real jobevents.Store append. Persisted observations are bounded snapshots,
// not process truth or authority to run or resume a job.
package jobrecorder

import (
	"context"
	"time"

	"github.com/BaiTian6641/Cloudy-Workspace/host/core/internal/bootidentity"
	"github.com/BaiTian6641/Cloudy-Workspace/host/core/internal/jobevents"
	"github.com/BaiTian6641/Cloudy-Workspace/host/core/internal/jobs"
)

// Failure is a fixed-safe wrapper. It never retains or unwraps an underlying
// error, so no raw OS, job or store cause crosses this boundary.
type Failure struct {
	Stage             string // capture-wait, capture-settle, append
	Code              string // invalid-input, invalid-snapshot, observation-failed, persistence-failed
	CompletionUnknown bool
	Claimed           bool
}

func (f *Failure) Error() string { return "job-recorder-" + f.Stage + ":" + f.Code }

// Metadata is caller-owned identity, copied into the observation. Nothing here
// is generated by this package.
type Metadata struct {
	EventID  string
	JobID    string
	Revision uint64
	BootID   bootidentity.ID
}

// Observation is an immutable value holding only whitelisted status fields.
// It carries no stdout/stderr buffers, no Failure pointers and no job/store
// references.
type Observation struct {
	valid      bool
	eventID    string
	jobID      string
	revision   uint64
	bootID     bootidentity.ID
	occurredAt time.Time

	outcome       string
	started       bool
	startResolved bool
	reaped        bool
	exitCode      int
	signal        int
	retirement    string
	ioCompletion  string
}

func validUUID(s string) bool {
	if len(s) != 36 {
		return false
	}
	for i := range s {
		c := s[i]
		if i == 8 || i == 13 || i == 18 || i == 23 {
			if c != '-' {
				return false
			}
		} else if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return false
		}
	}
	return s[14] == '4' && (s[19] == '8' || s[19] == '9' || s[19] == 'a' || s[19] == 'b')
}

func member(s string, values ...string) bool {
	for _, v := range values {
		if s == v {
			return true
		}
	}
	return false
}

func validMetadata(m Metadata) bool {
	if !validUUID(m.EventID) || !validUUID(m.JobID) {
		return false
	}
	if !validUUID(m.BootID.String()) {
		return false
	}
	return m.Revision >= 1 && m.Revision <= jobevents.MaxSequence
}

// validSnapshot enforces the jobs enum whitelist and Started/StartResolved/
// Reaped consistency plus legal exit/signal bounds when reaped, matching the
// record validation accepted upstream by jobevents.
func validSnapshot(s jobs.Snapshot) bool {
	if !member(s.Outcome, "pending", "rejected", "start-failed", "exited", "canceled", "timed-out") {
		return false
	}
	if !member(s.Retirement, "pending", "uncertain", "confirmed") {
		return false
	}
	if !member(s.IOCompletion, "pending", "complete", "not-assessed", "incomplete", "unknown") {
		return false
	}
	if s.Started && !s.StartResolved {
		return false
	}
	if s.Reaped && !s.Started {
		return false
	}
	if s.Reaped {
		return s.ExitCode >= -1 && int64(s.ExitCode) <= 1<<32-1 &&
			s.Signal >= 0 && int64(s.Signal) <= 1<<32-1
	}
	return true
}

// Per-call dependencies permit focused tests without mutable production globals.
func capture(observer func(*jobs.Job, context.Context) (jobs.Snapshot, error), now func() time.Time, stage string, ctx context.Context, job *jobs.Job, metadata Metadata) (Observation, error) {
	if ctx == nil {
		return Observation{}, &Failure{Stage: stage, Code: "invalid-input"}
	}
	if job == nil {
		return Observation{}, &Failure{Stage: stage, Code: "invalid-input"}
	}
	if !validMetadata(metadata) {
		return Observation{}, &Failure{Stage: stage, Code: "invalid-input"}
	}
	snap, obsErr := observer(job, ctx)
	at := now().UTC()
	if !validSnapshot(snap) {
		return Observation{}, &Failure{Stage: stage, Code: "invalid-snapshot"}
	}
	o := Observation{
		valid:         true,
		eventID:       metadata.EventID,
		jobID:         metadata.JobID,
		revision:      metadata.Revision,
		bootID:        metadata.BootID,
		occurredAt:    at,
		outcome:       snap.Outcome,
		started:       snap.Started,
		startResolved: snap.StartResolved,
		reaped:        snap.Reaped,
		retirement:    snap.Retirement,
		ioCompletion:  snap.IOCompletion,
	}
	if snap.Reaped {
		o.exitCode, o.signal = snap.ExitCode, snap.Signal
	}
	if obsErr != nil {
		// Uncertainty from the real Wait/Settle remains truthful: the caller
		// may still append this pending/uncertain snapshot. No completion or
		// persistence outcome is inferred from the observation error.
		return o, &Failure{Stage: stage, Code: "observation-failed", CompletionUnknown: true}
	}
	return o, nil
}

// CaptureWait performs exactly one real job.Wait against the caller's job.
// Observer cancellation never cancels the job; the caller owns its lifetime.
func CaptureWait(ctx context.Context, job *jobs.Job, metadata Metadata) (Observation, error) {
	return capture((*jobs.Job).Wait, time.Now, "capture-wait", ctx, job, metadata)
}

// CaptureSettle performs exactly one real job.Settle against the caller's
// job. Settle continues owned cleanup after a committed stop; it is not
// purely passive observation. The caller retains the Job until settlement;
// the independently borrowed Store still requires its own explicit Close.
func CaptureSettle(ctx context.Context, job *jobs.Job, metadata Metadata) (Observation, error) {
	return capture((*jobs.Job).Settle, time.Now, "capture-settle", ctx, job, metadata)
}

// AppendTo persists this captured observation via a real AppendJobStatus on
// every call, using exactly the captured fields; it never re-observes,
// re-settles, re-reads the clock, or generates IDs or revisions. A failed
// append returns a zero receipt and a wrapper failure; the store remains
// owned (and, per upstream, poisoned where applicable) by the caller.
func (o Observation) AppendTo(store *jobevents.Store) (jobevents.Receipt, error) {
	if store == nil {
		return jobevents.Receipt{}, &Failure{Stage: "append", Code: "invalid-input"}
	}
	if !o.valid {
		return jobevents.Receipt{}, &Failure{Stage: "append", Code: "invalid-input"}
	}
	// Rebuild from whitelisted captured fields only; any mutation of the
	// original job's outputs/failure after capture cannot reach persistence.
	input := jobevents.StatusInput{
		EventID:    o.eventID,
		JobID:      o.jobID,
		BootID:     o.bootID,
		Revision:   o.revision,
		OccurredAt: o.occurredAt,
		Observed: jobs.Snapshot{
			Outcome:       o.outcome,
			Started:       o.started,
			StartResolved: o.startResolved,
			Reaped:        o.reaped,
			ExitCode:      o.exitCode,
			Signal:        o.signal,
			Retirement:    o.retirement,
			IOCompletion:  o.ioCompletion,
		},
	}
	receipt, err := store.AppendJobStatus(input)
	if err != nil {
		return jobevents.Receipt{}, persistenceFailure(err)
	}
	return receipt, nil
}

// Copy only effect flags from the real store boundary, never its cause or text.
func persistenceFailure(err error) *Failure {
	f := &Failure{Stage: "append", Code: "persistence-failed"}
	if source, ok := err.(*jobevents.Failure); ok && source != nil {
		f.CompletionUnknown, f.Claimed = source.CompletionUnknown, source.Claimed
	}
	return f
}
