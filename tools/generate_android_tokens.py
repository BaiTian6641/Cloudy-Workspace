"""Generate the Android design constants from the canonical Cloudy token file."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "shared/design-system/tokens.json"
OUTPUT = ROOT / "shared/design-system/android/src/main/java/io/github/baitian6641/cloudy/design/CloudyTokens.kt"


def name(value: str) -> str:
    return "".join(part.capitalize() for part in value.replace("-", " ").split())


def render(tokens: dict) -> str:
    lines = ["// Generated by tools/generate_android_tokens.py; edit tokens.json instead.",
             "package io.github.baitian6641.cloudy.design", "", "internal object CloudyTokens {"]
    for theme, colors in tokens["themes"].items():
        lines.append(f"    object {name(theme)} {{")
        for key, value in colors.items():
            lines.append(f"        const val {name(key)} = 0xFF{value[1:]}L")
        lines.append("    }")
    for group in ("radii", "density", "motionMs"):
        lines.append(f"    object {name(group)} {{")
        for key, value in tokens[group].items():
            lines.append(f"        const val {name(key)} = {value}")
        lines.append("    }")
    for value in tokens["spacing"]:
        lines.append(f"    const val Space{value} = {value}")
    lines.append("    object Type {")
    for key, value in tokens["typography"].items():
        if isinstance(value, dict):
            for prop, number in value.items():
                lines.append(f"        const val {name(key)}{name(prop)} = {number}")
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render(json.loads(SOURCE.read_text()))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != expected:
            parser.exit(1, "Android tokens differ; run tools/generate_android_tokens.py\n")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(expected)


if __name__ == "__main__":
    main()
