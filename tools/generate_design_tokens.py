#!/usr/bin/env python3
"""Generate the offline specimen's color/metric variables from canonical data."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'shared/design-system/tokens.json'
DESTINATION = ROOT / 'docs/04-design/tokens.css'


def generated_css():
    tokens = json.loads(SOURCE.read_text())
    lines = ['/* Generated by tools/generate_design_tokens.py; edit tokens.json. */']
    for name, values in tokens['themes'].items():
        selector = ':root, [data-theme="light"]' if name == 'light' else '[data-theme="dark"]'
        lines.append(selector + ' {')
        lines.append('  color-scheme: ' + name + ';')
        lines.extend(f'  --cw-{key}: {value};' for key, value in values.items())
        lines.append('}')
    lines.append(':root {')
    lines.extend(f'  --cw-ansi-{key}: {value};' for key, value in tokens['ansi'].items())
    for role, value in tokens['radii'].items():
        lines.append(f'  --cw-radius-{role}: {value}px;')
    for role, value in tokens['motionMs'].items():
        lines.append(f'  --cw-motion-{role}: {value}ms;')
    for role, value in tokens['typography'].items():
        if isinstance(value, dict):
            lines.append(f'  --cw-type-{role}: {value["size"]}px;')
            lines.append(f'  --cw-line-{role}: {value["lineHeight"]}px;')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    expected = generated_css()
    if args.check:
        if not DESTINATION.exists() or DESTINATION.read_text() != expected:
            raise SystemExit('Generated tokens.css differs; run tools/generate_design_tokens.py')
        print('Generated CSS tokens match canonical data.')
    else:
        DESTINATION.write_text(expected)
        print('Generated docs/04-design/tokens.css')


if __name__ == '__main__':
    main()
