#!/usr/bin/env python3
"""Finite HTTPS fixture for P0-S2; not a production file server.

``prepare`` creates private TLS/config files without opening a listener. ``serve``
opens the explicitly configured IPv4/high port until interrupted. The only data
route is GET /fixture.bin; there is no filesystem serving, upload, or resume.
Generated bytes are SHA256(fixtureId + NUL + uint64_be(block_index)), repeated to
fill each 64 KiB block, with the last block truncated to the configured length.
Throttling changes delivery time, not content, and is not a performance result.

Primary contracts: https://docs.python.org/3.13/library/ssl.html,
https://docs.python.org/3.13/library/http.server.html,
https://docs.openssl.org/3.5/man1/openssl-req/ and
https://docs.openssl.org/3.5/man1/openssl-x509/ .
"""

import argparse
from datetime import datetime, timezone
import hashlib
import ipaddress
import json
import os
from pathlib import Path
import secrets
import socket
import ssl
import subprocess
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

FIXTURE_ID = "cloudy-uidt-sha256-blocks-v1"
BLOCK_BYTES = 65536
MAX_LENGTH_BYTES = 256 * 1024 * 1024
ROOT = Path(__file__).resolve().parents[1]


def utc_now():
    return datetime.now(timezone.utc).isoformat(timespec="milliseconds").replace("+00:00", "Z")


def validate_parameters(bind, port, length_bytes, bytes_per_second):
    """Reject wildcard/multicast binds and unbounded fixture parameters."""
    address = ipaddress.IPv4Address(bind)
    if address.is_unspecified or address.is_multicast or address.is_reserved:
        raise ValueError("bind must be one explicit unicast IPv4 address")
    for value in (port, length_bytes, bytes_per_second):
        if type(value) is not int:
            raise ValueError("port, length and rate must be integers")
    if not 1024 <= port <= 65535:
        raise ValueError("port must be in 1024..65535")
    if not 1 <= length_bytes <= MAX_LENGTH_BYTES:
        raise ValueError("length must be in 1..268435456 bytes")
    if not 0 <= bytes_per_second <= MAX_LENGTH_BYTES:
        raise ValueError("rate must be 0 (unthrottled) or at most 268435456 B/s")


def payload_chunks(length_bytes):
    """Generate a repeatable finite stream using at most one 64 KiB block."""
    if type(length_bytes) is not int or not 1 <= length_bytes <= MAX_LENGTH_BYTES:
        raise ValueError("length must be in 1..268435456 bytes")
    remaining = length_bytes
    block_index = 0
    while remaining:
        digest = hashlib.sha256(
            FIXTURE_ID.encode("ascii") + b"\0" + block_index.to_bytes(8, "big")
        ).digest()
        chunk = (digest * (BLOCK_BYTES // len(digest)))[:min(remaining, BLOCK_BYTES)]
        yield chunk
        remaining -= len(chunk)
        block_index += 1


def payload_sha256(length_bytes):
    digest = hashlib.sha256()
    for chunk in payload_chunks(length_bytes):
        digest.update(chunk)
    return digest.hexdigest()


def private_path(path):
    """Inside this checkout, generated files must stay in an ignored subtree."""
    resolved = Path(path).expanduser().resolve()
    if resolved.is_relative_to(ROOT):
        allowed = (ROOT / ".cache", ROOT / "qualification/results/private")
        if not any(resolved.is_relative_to(base) and resolved != base for base in allowed):
            raise ValueError("use a new subdirectory of .cache or qualification/results/private")
    return resolved


def write_private(path, text):
    with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), "w") as stream:
        stream.write(text)


def run_openssl(directory, *arguments):
    # OpenSSL writes only into the new 0700 directory, under a child-only umask.
    # No shell expansion, process-global umask change, or key text is logged.
    result = subprocess.run(
        ["openssl", *arguments], cwd=directory, umask=0o077, check=False,
        stdout=subprocess.DEVNULL, stderr=subprocess.PIPE, timeout=30,
    )
    if result.returncode:
        raise RuntimeError(f"OpenSSL certificate generation failed (exit {result.returncode})")


def prepare(directory, bind, port, length_bytes=64 * 1024 * 1024, bytes_per_second=0):
    """Create a new private fixture; existing files are never overwritten."""
    validate_parameters(bind, port, length_bytes, bytes_per_second)
    directory = private_path(directory)
    directory.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
    directory.mkdir(mode=0o700)
    run_openssl(
        directory, "req", "-new", "-x509", "-newkey", "rsa:2048", "-noenc",
        "-keyout", "ca.key", "-out", "ca.pem", "-days", "2", "-sha256",
        "-subj", "/CN=Cloudy UIDT fixture CA",
        "-addext", "basicConstraints=critical,CA:TRUE,pathlen:0",
        "-addext", "keyUsage=critical,keyCertSign,cRLSign",
        "-addext", "subjectKeyIdentifier=hash",
    )
    run_openssl(
        directory, "req", "-new", "-newkey", "rsa:2048", "-noenc",
        "-keyout", "server.key", "-out", "server.csr",
        "-subj", "/CN=Cloudy UIDT fixture server",
    )
    write_private(directory / "server.ext", "\n".join([
        "basicConstraints=critical,CA:FALSE",
        "keyUsage=critical,digitalSignature,keyEncipherment",
        "extendedKeyUsage=serverAuth",
        "subjectKeyIdentifier=hash",
        "authorityKeyIdentifier=keyid,issuer",
        f"subjectAltName=IP:{bind}", "",
    ]))
    run_openssl(
        directory, "x509", "-req", "-in", "server.csr", "-CA", "ca.pem",
        "-CAkey", "ca.key", "-set_serial", str(secrets.randbits(159) + 1),
        "-out", "server.pem", "-days", "2", "-sha256", "-extfile", "server.ext",
    )
    android_config = {
        "schemaVersion": 1,
        "fixtureId": FIXTURE_ID,
        "url": f"https://{bind}:{port}/fixture.bin",
        "expectedLengthBytes": length_bytes,
        "expectedSha256": payload_sha256(length_bytes),
        "caCertificatePem": (directory / "ca.pem").read_text(encoding="ascii"),
    }
    host_config = {
        "schemaVersion": 1, "bind": bind, "port": port,
        "lengthBytes": length_bytes, "bytesPerSecond": bytes_per_second,
    }
    for filename, data in (("android-config.json", android_config), ("host-config.json", host_config)):
        write_private(directory / filename, json.dumps(data, indent=2) + "\n")
    return android_config


def read_private(path):
    if path.is_symlink() or not path.is_file() or path.stat().st_mode & 0o077:
        raise ValueError("fixture files must be regular, non-symlinked and owner-only")
    return path.read_text(encoding="utf-8")


class FixtureServer(ThreadingHTTPServer):
    """A bounded-thread TLS endpoint; sockets and data are fixture-only."""

    daemon_threads = False
    request_queue_size = 4

    def __init__(self, directory, event_sink=None):
        directory = private_path(directory)
        if directory.stat().st_mode & 0o077:
            raise ValueError("fixture directory must be owner-only")
        config = json.loads(read_private(directory / "host-config.json"))
        self.length_bytes = config["lengthBytes"]
        self.bytes_per_second = config["bytesPerSecond"]
        validate_parameters(config["bind"], config["port"], self.length_bytes, self.bytes_per_second)
        if config["schemaVersion"] != 1:
            raise ValueError("unsupported host config schema")
        self.sha256 = payload_sha256(self.length_bytes)
        android = json.loads(read_private(directory / "android-config.json"))
        expected = {
            "schemaVersion": 1, "fixtureId": FIXTURE_ID,
            "url": f"https://{config['bind']}:{config['port']}/fixture.bin",
            "expectedLengthBytes": self.length_bytes, "expectedSha256": self.sha256,
            "caCertificatePem": read_private(directory / "ca.pem"),
        }
        if android != expected:
            raise ValueError("Android config does not match this fixture")
        for filename in ("server.pem", "server.key"):
            read_private(directory / filename)
        self.tls_context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
        self.tls_context.minimum_version = ssl.TLSVersion.TLSv1_2
        self.tls_context.load_cert_chain(directory / "server.pem", directory / "server.key")
        self.stop_event = threading.Event()
        self.slots = threading.BoundedSemaphore(4)
        self.connections = set()
        self.connections_lock = threading.Lock()
        self.event_lock = threading.Lock()
        self.event_sink = event_sink or (lambda event: print(json.dumps(event), flush=True))
        super().__init__((config["bind"], config["port"]), FixtureHandler)

    def get_request(self):
        connection, address = super().get_request()
        connection.settimeout(10)
        try:
            # Handshake happens in the bounded request thread, so a client that
            # never sends TLS cannot block every other connection at accept().
            return self.tls_context.wrap_socket(
                connection, server_side=True, do_handshake_on_connect=False,
            ), address
        except OSError:
            connection.close()
            raise

    def process_request(self, request, client_address):
        if not self.slots.acquire(blocking=False):
            self.shutdown_request(request)
            return
        with self.connections_lock:
            self.connections.add(request)
        try:
            super().process_request(request, client_address)
        except Exception:
            with self.connections_lock:
                self.connections.discard(request)
            self.slots.release()
            raise

    def process_request_thread(self, request, client_address):
        try:
            super().process_request_thread(request, client_address)
        finally:
            with self.connections_lock:
                self.connections.discard(request)
            self.slots.release()

    def handle_error(self, request, client_address):
        # Never emit client addresses, attacker-supplied paths, or TLS material.
        self.emit({"event": "connection_error", "atUtc": utc_now(),
                   "error": sys.exc_info()[0].__name__})

    def emit(self, event):
        with self.event_lock:
            self.event_sink(event)

    def server_close(self):
        self.stop_event.set()
        # Interrupt reads/handshakes/writes as well as throttle waits before the
        # mixin joins all non-daemon workers. No ten-second sleeper is left behind.
        with self.connections_lock:
            active = tuple(self.connections)
        for connection in active:
            try:
                connection.shutdown(socket.SHUT_RDWR)
            except OSError:
                pass
        super().server_close()


class FixtureHandler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.0"
    server_version = "CloudyFixture/1"
    sys_version = ""

    def setup(self):
        super().setup()
        self.request_id = secrets.token_hex(16)

    def log_message(self, format, *args):
        # Base logging includes addresses and request targets; omit it entirely.
        pass

    def parse_request(self):
        if not super().parse_request():
            return False
        if self.command != "GET":
            self.reject(405)
            return False
        # BaseHTTPRequestHandler normalizes leading //; check the original target
        # so aliases, query strings and encoded filesystem paths are all refused.
        if self.requestline.split()[1] != "/fixture.bin":
            self.reject(404)
            return False
        if (self.headers.get("Transfer-Encoding") is not None
                or self.headers.get("Content-Length") not in (None, "0")
                or self.headers.get("Range") is not None):
            self.reject(400)
            return False
        return True

    def reject(self, status):
        self.send_response(status)
        self.send_header("Content-Length", "0")
        self.send_header("Connection", "close")
        if status == 405:
            self.send_header("Allow", "GET")
        self.end_headers()
        self.server.emit({"event": "rejected", "requestId": self.request_id,
                          "atUtc": utc_now(), "status": status})

    def do_GET(self):
        sent = 0
        started = time.monotonic()
        outcome = "interrupted"
        self.server.emit({"event": "request_started", "requestId": self.request_id,
                          "atUtc": utc_now(), "expectedLengthBytes": self.server.length_bytes})
        try:
            self.send_response(200)
            self.send_header("Content-Type", "application/octet-stream")
            self.send_header("Content-Length", str(self.server.length_bytes))
            self.send_header("X-Fixture-SHA256", self.server.sha256)
            self.send_header("Cache-Control", "no-store")
            self.send_header("Connection", "close")
            self.end_headers()
            for chunk in payload_chunks(self.server.length_bytes):
                if self.server.bytes_per_second:
                    delay = max(0, (sent + len(chunk)) / self.server.bytes_per_second
                                - (time.monotonic() - started))
                    if self.server.stop_event.wait(delay):
                        break
                if self.server.stop_event.is_set():
                    break
                self.wfile.write(chunk)
                sent += len(chunk)
            if sent == self.server.length_bytes:
                outcome = "stream_written"
        except (OSError, TimeoutError):
            outcome = "connection_interrupted"
        finally:
            # Writes accepted by the local TLS socket do not prove client receipt
            # or durable file completion; the Android hash is separate evidence.
            self.server.emit({"event": outcome, "requestId": self.request_id,
                              "atUtc": utc_now(), "bytesWritten": sent})


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="action", required=True)
    create = subparsers.add_parser("prepare", help="create new private config/certificates; no listener")
    create.add_argument("--private-dir", required=True, type=Path)
    create.add_argument("--bind", required=True)
    create.add_argument("--port", required=True, type=int)
    create.add_argument("--length-bytes", type=int, default=64 * 1024 * 1024)
    create.add_argument("--bytes-per-second", type=int, default=0)
    serve = subparsers.add_parser("serve", help="serve the explicitly configured temporary fixture")
    serve.add_argument("--private-dir", required=True, type=Path)
    args = parser.parse_args(argv)
    try:
        if args.action == "prepare":
            prepare(args.private_dir, args.bind, args.port, args.length_bytes, args.bytes_per_second)
            print("Prepared private android-config.json and TLS files; no listener started.")
        else:
            with FixtureServer(args.private_dir) as server:
                print("Temporary HTTPS fixture running; Ctrl-C stops it.", flush=True)
                try:
                    server.serve_forever(poll_interval=0.2)
                except KeyboardInterrupt:
                    pass
    except (OSError, ValueError, KeyError, RuntimeError, subprocess.TimeoutExpired) as error:
        # Avoid dumping a private path/config in CLI diagnostics.
        print(f"Fixture failed: {type(error).__name__}. Check private inputs and availability.", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
